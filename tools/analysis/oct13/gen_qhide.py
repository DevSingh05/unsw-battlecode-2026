#!/usr/bin/env python3
"""gen_qhide.py: write bot/qhide_data.hpp (the QHIDE table) from work/oct13/hide_spots.json (hide.py --top 6 --emit).

Per map: among the quietest spots, the nearest one whose exposure is within 3 points of the best. The entry order is the
QHIDE bit order and must not change (append only). Look-alike maps share an entry (same size and queen start tiles).

Run from /Users/devsingh/Developer/UNSW_Battlecode:
    python3 tools/analysis/oct13/hide.py --top 6 --emit work/oct13/hide_spots.json && python3 tools/analysis/oct13/gen_qhide.py"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
ORDER = ["Whale Song", "Troll Australia", "Maelstrom", "Hive", "Slithery Fight", "Islands", "Around UNSW", "Devil", "Trophy",
         "Queen Of Spades", "Autarky", "Thermopylae", "Metro", "Athena", "Ezam", "Default", "Stripes", "weakhold", "Ouroboros",
         "Trolley Problem (Buffed)", "Tower Defense", "Prisoners Dilemma"]
ALSO = {"Troll Australia": "Australia", "Ezam": "Maze"}  # look-alikes covered by the same entry
key = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
S = {key(k): v for k, v in json.loads((ROOT / "work/oct13/hide_spots.json").read_text()).items()}
rows = []
for i, name in enumerate(ORDER):
    e = S[key(name)]
    best = e["spots"][0]["exp"]
    ok = [s for s in e["spots"] if s["exp"] <= best + 0.03]
    s = e["spots"][0] if name in ALSO else min(ok, key=lambda s: s["steps"])  # a shared entry takes the best spot (first on both maps)
    other = ""
    if name in ALSO:
        o = S[key(ALSO[name])]
        assert o["spawn"] == e["spawn"] and (o["w"], o["h"]) == (e["w"], e["h"]), name
        m = [x for x in o["spots"] if x["tile"] == s["tile"]]
        other = f"; {ALSO[name]}: " + (f"{100 * m[0]['exp']:.1f}%" if m else "not in its top 6")
    rows.append(f"    {{\"{name}\", {e['w']}, {e['h']}, {{{e['spawn'][0]}, {e['spawn'][1]}}}, {{{s['tile'][0]}, {s['tile'][1]}}}}}, "
                f"// {i}: ({s['xy'][0]},{s['xy'][1]}), {s['steps']} steps; exposure {100 * s['exp']:.1f}% (leash area {100 * e['leash']:.1f}%){other}")
out = """// Generated by tools/analysis/oct13/gen_qhide.py from the enemy-traffic study (tools/analysis/oct13/traffic.py). Do not edit.
// QHIDE table: for a map of this size whose queen starts on spawn[k], the quiet tile hide[k] she walks to and circles.
// "exposure" = share of sampled rounds (r30+, side that lost the game) in which the tile's 2-step neighbourhood was
// inside an enemy lunge range; "leash area" = the same for the tiles within 8 steps of her start.
#pragma once
struct QHideSpot { const char* name; int w, h; int spawn[2]; int hide[2]; };
static const QHideSpot QHIDE_SPOTS[] = {
""" + "\n".join(rows) + """
};
static const int QHIDE_COUNT = sizeof(QHIDE_SPOTS) / sizeof(QHIDE_SPOTS[0]);
"""
(ROOT / "bot/qhide_data.hpp").write_text(out)
print(out)
