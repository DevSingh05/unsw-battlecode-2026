#!/usr/bin/env python3
"""gen_qhide.py: write bot/qhide_data.hpp (the QHIDE table) from work/oct13/hide_spots.json (hide.py --top 6 --emit).

Per map: among the quietest spots, the nearest one whose exposure is within 3 points of the best. The entry order is the
QHIDE bit order and must not change (append only). Look-alike maps share an entry (same size and queen start tiles).

Run from /Users/devsingh/Developer/UNSW_Battlecode:
    python3 tools/analysis/oct13/hide.py --top 6 --emit work/oct13/hide_spots.json && python3 tools/analysis/oct13/gen_qhide.py"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
ORDER = ["Whale Song", "Troll Australia", "Maelstrom", "Hive", "Slithery Fight", "Islands", "Around UNSW", "Devil", "Trophy",
         "Queen Of Spades", "Autarky", "Thermopylae", "Metro", "Athena", "Ezam", "Default", "Stripes", "weakhold", "Ouroboros",
         "Trolley Problem (Buffed)", "Tower Defense", "Prisoners Dilemma"]
ALSO = {"Troll Australia": "Australia", "Ezam": "Maze"}  # look-alikes covered by the same entry
# Spots fixed by local play against km6 (work/oct12/results/t34_hide, t35_hide2): the far, empty corner beat the
# nearer quiet tile, where allied traffic boxes the queen (deaths on her own neck or on an ally's body). (x, y) is the
# tile for the queen that starts on spawn[0]; the other side gets its mirror image.
FIXED = {"Hive": (0, 0), "Devil": (0, 0), "Around UNSW": (8, 45), "Queen Of Spades": (5, 26), "Whale Song": (14, 12)}
# A shared entry can be switched off for one of its look-alikes once that map is the adopted one.
SKIP = {"Troll Australia": "Troll Australia"}  # (32,5) won 9-1 on Australia and lost 3-7 on Troll Australia against km6
key = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
S = {key(k): v for k, v in json.loads((ROOT / "work/oct13/hide_spots.json").read_text()).items()}
# symmetry, plain walking distance from spawn[0] and per-tile exposure (side that lost) for the FIXED spots
import sys
sys.path.insert(0, str(ROOT / "notes" / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "analysis" / "oct13"))
import replay_sim as RS  # noqa: E402
import traffic as TR  # noqa: E402
import hide as HD  # noqa: E402
SIG, DIST, EXP = {}, {}, {}
for name in FIXED:
    mp = next(p for p in (ROOT / "maps" / "server_live31").glob("*.map") if key(p.stem) == key(name))
    m = RS.Map(mp.read_text())
    g = json.loads(next(f for f in (ROOT / "work/oct13/traffic").glob("*.json") if key(f.stem) == key(name)).read_text())
    SIG[key(name)] = TR.symmetry(m)
    DIST[key(name)] = TR.bfs_from(HD.plain_graph(m), g["spawn"])
    EXP[key(name)] = [v / (g["nl"] or 1) for v in g["lost"]]
rows = []
for i, name in enumerate(ORDER):
    e = S[key(name)]
    best = e["spots"][0]["exp"]
    ok = [s for s in e["spots"] if s["exp"] <= best + 0.03]
    s = e["spots"][0] if name in ALSO else min(ok, key=lambda s: s["steps"])  # a shared entry takes the best spot (first on both maps)
    if name in FIXED:
        x, y = FIXED[name]
        t = y * e["w"] + x
        s = {"tile": [t, SIG[key(name)][t]], "xy": [x, y], "steps": DIST[key(name)].get(t, -1), "exp": EXP[key(name)][t], "fixed": True}
    other = ""
    if name in ALSO:
        o = S[key(ALSO[name])]
        assert o["spawn"] == e["spawn"] and (o["w"], o["h"]) == (e["w"], e["h"]), name
        m = [x for x in o["spots"] if x["tile"] == s["tile"]]
        other = f"; {ALSO[name]}: " + (f"{100 * m[0]['exp']:.1f}%" if m else "not in its top 6")
    skip = f'"{SKIP[name]}"' if name in SKIP else "nullptr"
    rows.append(f"    {{\"{name}\", {e['w']}, {e['h']}, {{{e['spawn'][0]}, {e['spawn'][1]}}}, {{{s['tile'][0]}, {s['tile'][1]}}}, {skip}}}, "
                f"// {i}: ({s['xy'][0]},{s['xy'][1]}), {s['steps']} steps; exposure {100 * s['exp']:.1f}% (leash area {100 * e['leash']:.1f}%){other}{'; fixed by local play' if s.get('fixed') else ''}")
out = """// Generated by tools/analysis/oct13/gen_qhide.py from the enemy-traffic study (tools/analysis/oct13/traffic.py). Do not edit.
// QHIDE table: for a map of this size whose queen starts on spawn[k], the quiet tile hide[k] she walks to and circles.
// "exposure" = share of sampled rounds (r30+, side that lost the game) in which the tile's 2-step neighbourhood was
// inside an enemy lunge range; "leash area" = the same for the tiles within 8 steps of her start.
#pragma once
// skip: while the adopted map has this name the entry is not used (a look-alike on which the spot lost).
struct QHideSpot { const char* name; int w, h; int spawn[2]; int hide[2]; const char* skip; };
static const QHideSpot QHIDE_SPOTS[] = {
""" + "\n".join(rows) + """
};
static const int QHIDE_COUNT = sizeof(QHIDE_SPOTS) / sizeof(QHIDE_SPOTS[0]);
"""
(ROOT / "bot/qhide_data.hpp").write_text(out)
print(out)
