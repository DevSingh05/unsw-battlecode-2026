#!/usr/bin/env python3
"""Compile .map files into bot/maps_data.hpp so every dragon knows the whole map.

For each map we emit: size, symmetry, the tile reached by stepping N/E/S/W from
every tile (-1 for kelp, portals resolved), per-tile pearl gap range, and the
starting dragons (used to recognise the map from our id + head position).
Mirrors engine/src/config.cc + helpers.cc exactly.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = "NESW"
OFF = {"N": (0, -1), "E": (1, 0), "S": (0, 1), "W": (-1, 0)}


def parse(path):
    w = h = 0
    sym = "none"
    name = path.stem
    tiles = {}
    edges = {}  # (orient 'H'/'V', x, y) -> (kind, pid)
    portal_ends = {}
    dragons = []
    unit_limit = 64
    for raw in path.read_text().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line == "END":
            break
        f = line.split()
        k = f[0]
        if k == "MAP":
            w, h = int(f[1]), int(f[2])
        elif k == "SYMMETRY":
            sym = f[1]
        elif k == "MAP_NAME":
            name = line[len("MAP_NAME"):].strip()
        elif k == "UNIT_LIMIT":
            unit_limit = int(f[1])
        elif k == "TILE":
            x, y, mn, mx = map(int, f[1:5])
            tiles[(x, y)] = (mn, mx)
        elif k == "EDGE":
            idx, kind, pid = int(f[1]), int(f[2]), int(f[3])
            stride = w + 1
            col, row = idx % stride, idx // stride
            if row % 2 == 0:
                if col == w or row == 2 * h:
                    continue
                key = ("H", col, row // 2)
            else:
                if col == w:
                    continue
                key = ("V", col, (row - 1) // 2)
            if kind == 2:
                old = edges.get(key)
                if old and old[0] == 2:
                    pid_eff = min(old[1], pid)
                else:
                    pid_eff = pid
                edges[key] = (2, pid_eff)
                portal_ends.setdefault(pid, []).append(key)
            else:
                edges[key] = (kind, -1)
        elif k == "DRAGON":
            team, n = int(f[1]), int(f[2])
            pts = [(int(f[3 + 2 * i]), int(f[4 + 2 * i])) for i in range(n)]
            dragons.append((team, pts))
    partner = {}
    for pid, ends in portal_ends.items():
        if len(ends) == 2:
            partner[ends[0]] = ends[1]
            partner[ends[1]] = ends[0]

    def wrap(x, y):
        return x % w, y % h

    def side_edge(x, y, d):
        if d == "N":
            return ("H", x, y)
        if d == "S":
            return ("H", x, (y + 1) % h)
        if d == "W":
            return ("V", x, y)
        return ("V", (x + 1) % w, y)

    def after_crossing(e, d):
        o, ex, ey = e
        if o == "H":
            return wrap(ex, ey if d == "S" else ey - 1)
        return wrap(ex if d == "E" else ex - 1, ey)

    nxt = []
    for y in range(h):
        for x in range(w):
            for d in DIRS:
                e = side_edge(x, y, d)
                kind, _ = edges.get(e, (0, -1))
                if kind == 1:
                    nxt.append(-1)
                elif kind == 2:
                    tx, ty = after_crossing(partner[e], d)
                    nxt.append(ty * w + tx)
                else:
                    tx, ty = wrap(x + OFF[d][0], y + OFF[d][1])
                    nxt.append(ty * w + tx)
    gmin = []
    gmax = []
    for y in range(h):
        for x in range(w):
            mn, mx = tiles.get((x, y), (0, 0))
            gmin.append(mn)
            gmax.append(mx)
    return dict(name=name, w=w, h=h, sym=sym, nxt=nxt, gmin=gmin, gmax=gmax,
                dragons=dragons, unit_limit=unit_limit)


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "notes" / "maps"
    out = ROOT / "bot" / "maps_data.hpp"
    # current ranked pool first, so ambiguous look-alikes resolve to a ranked map
    ranked_ids = {"id13", "id9", "id20", "id4", "id7", "id11", "id19", "id17", "id21", "id15"}
    paths = sorted(src.glob("*.map"), key=lambda p: (p.stem.split("__")[-1] not in ranked_ids, p.stem))
    maps = [parse(p) for p in paths]
    symcode = {"none": 0, "x": 1, "y": 2, "xy": 3}
    lines = ["// Generated by tools/genmaps.py. Do not edit.", "#pragma once", "#include <cstdint>", ""]
    for i, m in enumerate(maps):
        lines.append(f"// {m['name']} {m['w']}x{m['h']}")
        lines.append(f"static const int16_t MAP{i}_NXT[] = {{{','.join(map(str, m['nxt']))}}};")
        lines.append(f"static const uint16_t MAP{i}_GMIN[] = {{{','.join(map(str, m['gmin']))}}};")
        lines.append(f"static const uint16_t MAP{i}_GMAX[] = {{{','.join(map(str, m['gmax']))}}};")
        flat = []
        for team, pts in m["dragons"]:
            flat += [team, len(pts), pts[0][0], pts[0][1]]
        lines.append(f"static const int16_t MAP{i}_DRAGONS[] = {{{','.join(map(str, flat)) or '0'}}};")
    lines.append("")
    lines.append("struct KnownMap { const char* name; int w, h, sym, unitLimit, dragonCount;"
                 " const int16_t* nxt; const uint16_t* gmin; const uint16_t* gmax; const int16_t* dragons; };")
    lines.append("static const KnownMap KNOWN_MAPS[] = {")
    for i, m in enumerate(maps):
        nm = m["name"].replace('"', "")
        lines.append(f'  {{"{nm}", {m["w"]}, {m["h"]}, {symcode[m["sym"]]}, {m["unit_limit"]}, {len(m["dragons"])},'
                     f" MAP{i}_NXT, MAP{i}_GMIN, MAP{i}_GMAX, MAP{i}_DRAGONS}},")
    lines.append("};")
    lines.append(f"static const int KNOWN_MAP_COUNT = {len(maps)};")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} with {len(maps)} maps ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
